wf = File.read('.github/workflows/bootstrap-nilx-identity-fresh.yml')
runtime = File.read('deploy/nilx-identity-fresh/activate.sh')
def contract(condition, message)
  abort message unless condition
end

contract(wf.include?("on:\n  workflow_dispatch:"), 'manual-only workflow')
contract(!wf.include?('repository_dispatch'), 'no cross-repo automatic delivery')
contract(wf.include?("github.ref == 'refs/heads/master'"), 'trusted branch')
contract(wf.include?("deployment: ${{ inputs.operation == 'activate' }}"), 'validate is not a deploy')
contract(wf.include?('test "$SSH_HOST" = 158.220.74.54'), 'sole VPS pin')
contract(wf.include?('test "$SSH_USER" = deploy'), 'least-privilege deploy user')
contract(wf.include?('SSH_HOST_ED25519_PUBKEY'), 'host key pinning')
contract(wf.include?('FRESH_IDENTITY'), 'explicit first-use consent')
contract(wf.include?('gh attestation verify'), 'verify provenance')
contract(wf.include?('package-identity-service.yml'), 'Identity image provenance')
contract(wf.include?('package-fresh-identity-secrets.yml'), 'signed product credential provenance')
contract(wf.include?('ghcr.io/nilx-one/0x1-identity-fresh-secrets@sha256'), 'immutable encrypted artifact')
contract(wf.include?('260af14f493783ee773e5df832d5aede2a04eae8'), 'pinned runtime source')
contract(wf.include?('jq -e'), 'real AIS product client check')
contract(!wf.include?('INFRA_DEPLOY_TOKEN'), 'no PAT needed')
contract(!wf.include?('secrets.TELOXIDE_TOKEN'), 'bot token must not come from Infra')
contract(!wf.include?('TELEGRAM_BOT_TOKEN'), 'no product token in Infra action environment')
contract(wf.include?('docker cp "$cid:/secrets.age"'), 'encrypted artifact only')
contract(wf.include?('scp -q'), 'SSH-pinned encrypted delivery')
contract(!wf.include?('age --decrypt'), 'Infra runner must not decrypt product secrets')
contract(runtime.include?('age --decrypt --identity "$key_file"'), 'only host decrypts')
contract(runtime.include?('age-keygen -y "$key_file"'), 'host generates product recipient')
contract(runtime.include?('nilxone-identity-fresh-data'), 'isolated new persistent volume')
contract(runtime.include?('--network-alias nilxone-identity'), 'compatible Web upstream')
contract(runtime.include?('AIAIAIAI_SIGN_IN_ISSUER=https://auth.aiaiaiai.org'), 'AIS is issuer')
contract(runtime.include?('PUBLIC_ORIGIN=https://nilx.one'), 'same-origin callback')
contract(runtime.include?('NATIVE_AUTH_SECRET='), 'host-owned native key')
contract(runtime.include?('PASSWORD_PEPPER='), 'host-owned password pepper')
contract(runtime.include?('GITHUB_EVIDENCE_ENCRYPTION_KEY='), 'host-owned evidence key')
contract(runtime.include?('mv --no-clobber'), 'secret file is not overwritten')
contract(!runtime.include?('nilxone-identity-data:/data'), 'never mount legacy volume')
contract(!runtime.include?('--publish'), 'no public Identity port')
contract(!runtime.include?('MARKET_TELEGRAM_ISSUER_URL='), 'purchase queue not enabled')
contract(!runtime.include?('NILX_BROWSER_HANDOFF_TOKEN='), 'no issuer worker')
contract(!runtime.include?('docker volume rm'), 'never delete state')
puts 'Product-owned secret envelope and host-only Identity bootstrap boundaries: OK'
